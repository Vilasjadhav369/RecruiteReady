// Generates src/styles/theme-dark.css (Swiss dark: black surfaces, white as the brand colour).
// Run: npm run gen:dark-theme
import fs from "node:fs";
const theme = fs.readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const get = (fam, n) => theme.match(new RegExp(`--color-${fam}-${n}:\\s*([^;]+);`))?.[1];
const base = "#111111";
const slate = { 50: "#121212", 100: "#1A1A1A", 200: "#262626", 300: "#333333", 400: "#7A7A7A", 500: "#8F8F8F", 600: "#A8A8A8", 700: "#C4C4C4", 800: "#DEDEDE", 900: "#F5F5F5", 950: "#FFFFFF" };
const D = '[data-theme="dark"]';
let out = `/* AUTO-GENERATED by scripts/gen-dark-theme.mjs — do not edit by hand. */\n${D} {\n  color-scheme: dark;\n  --rr-bg:#0A0A0A; --rr-surface:#111111; --rr-surface-2:#1A1A1A; --rr-border:#262626;\n`;
for (const [k, v] of Object.entries(slate)) out += `  --color-slate-${k}: ${v};\n`;
out += `  --color-background:#0A0A0A; --color-bg:#0A0A0A; --color-brand-bg:#0A0A0A;
  --color-surface:#111111; --color-brand-surface:#111111;
  --color-ink:#F5F5F5; --color-ink-2:#A8A8A8; --color-ink-3:#8F8F8F;
  --color-text-primary:#F5F5F5; --color-text-secondary:#A8A8A8; --color-text-muted:#8F8F8F; --color-text:#F5F5F5;
  --color-brand-text:#F5F5F5; --color-brand-text-secondary:#A8A8A8; --color-brand-text-muted:#8F8F8F; --color-brand-navy:#F5F5F5; --color-navy:#F5F5F5;
  --color-border:#262626; --color-border-soft:#1A1A1A; --color-brand-border:#262626;
  --color-primary:#FFFFFF; --color-primary-dark:#E5E5E5; --color-primary-darker:#D4D4D4; --color-primary-light:#D4D4D4;
  --color-brand-green:#FFFFFF; --color-brand-green-dark:#E5E5E5; --color-brand-blue:#FFFFFF; --color-brand-blue-dark:#E5E5E5; --color-royal:#FFFFFF;
  --color-primary-soft: color-mix(in oklab, #FFFFFF 7%, ${base});
  --color-primary-tint: color-mix(in oklab, #FFFFFF 13%, ${base});
  --color-primary-border: color-mix(in oklab, #FFFFFF 26%, ${base});
  --color-brand-mint-soft: var(--color-primary-soft); --color-brand-mint: var(--color-primary-tint);
  --color-light-blue: var(--color-primary-soft); --color-brand-blue-light: var(--color-primary-soft);
`;
// Neutral families (blue/indigo/sky/violet/purple/cyan were remapped to neutral in light)
for (const f of ["blue", "indigo", "sky", "violet", "purple", "cyan"]) {
  out += `  --color-${f}-50: color-mix(in oklab, #FFFFFF 6%, ${base}); --color-${f}-100: color-mix(in oklab, #FFFFFF 11%, ${base}); --color-${f}-200: color-mix(in oklab, #FFFFFF 20%, ${base});\n`;
  out += `  --color-${f}-300:#4A4A4A; --color-${f}-400:#7A7A7A; --color-${f}-500:#8F8F8F; --color-${f}-600:#A8A8A8; --color-${f}-700:#C4C4C4; --color-${f}-800:#DEDEDE; --color-${f}-900:#F5F5F5;\n`;
}
// Status families keep their hue: tints become translucent-on-surface, text shades get lighter
const status = { emerald: "#10b981", green: "#22c55e", amber: "#f59e0b", orange: "#f97316", yellow: "#eab308", rose: "#f43f5e", red: "#ef4444", teal: "#14b8a6" };
for (const [f, hex] of Object.entries(status)) {
  out += `  --color-${f}-50: color-mix(in oklab, ${hex} 12%, ${base}); --color-${f}-100: color-mix(in oklab, ${hex} 20%, ${base}); --color-${f}-200: color-mix(in oklab, ${hex} 34%, ${base});\n`;
  for (const [n, from] of [[600, 400], [700, 300], [800, 200], [900, 100]]) {
    const v = get(f, from); if (v) out += `  --color-${f}-${n}: ${v};\n`;
    const o = get(f, n); if (o) out += `  --rr-o-${f}-${n}: ${o};\n`;
  }
  out += `  --rr-o-${f}-500: ${get(f, 500)};\n`;
}
out += `}\n\n`;
out += `/* Surfaces */
${D} .bg-white, ${D} .hover\\:bg-white:hover, ${D} .focus\\:bg-white:focus { background-color: var(--rr-surface); }
${D} .bg-white\\/95 { background-color: color-mix(in oklab, var(--rr-surface) 95%, transparent); }
${D} .bg-white\\/90 { background-color: color-mix(in oklab, var(--rr-surface) 90%, transparent); }
${D} .bg-white\\/80 { background-color: color-mix(in oklab, var(--rr-surface) 80%, transparent); }
${D} .bg-white\\/70 { background-color: color-mix(in oklab, var(--rr-surface) 70%, transparent); }
${D} .bg-white\\/60 { background-color: color-mix(in oklab, var(--rr-surface) 60%, transparent); }
${D} .from-white { --tw-gradient-from: var(--rr-surface); }
${D} .via-white { --tw-gradient-via: var(--rr-surface); }
${D} .ring-white { --tw-ring-color: var(--rr-surface); }
/* Intentionally-dark panels stay dark */
${D} .bg-slate-950 { background-color: #000000; }
${D} .bg-slate-900 { background-color: #1A1A1A; }
${D} .bg-slate-800 { background-color: #262626; }
${D} .bg-slate-900\\/40 { background-color: rgb(0 0 0 / .6); }
${D} .bg-slate-900\\/50 { background-color: rgb(0 0 0 / .68); }
${D} .hover\\:bg-slate-800:hover { background-color: #2E2E2E; }
${D} .hover\\:bg-slate-700:hover { background-color: #333333; }
${D} .active\\:bg-slate-950:active { background-color: #000000; }
${D} .border-slate-900, ${D} .border-slate-800 { border-color: #262626; }
${D} .border-slate-700 { border-color: #333333; }
${D} .hover\\:border-slate-600:hover { border-color: #4A4A4A; }
/* Light text that sits on dark panels must stay light */
${D} .text-slate-100 { color: #F1F1F1; }
${D} .text-slate-200, ${D} .hover\\:text-slate-200:hover { color: #E2E2E2; }
${D} .text-slate-300 { color: #C9C9C9; }
/* Brand = white in dark; filled brand surfaces need dark text */
${D} .text-primary, ${D} .text-brand, ${D} .text-primary-dark, ${D} .hover\\:text-primary-dark:hover, ${D} .text-brand-dark, ${D} .hover\\:text-primary-hover:hover, ${D} .group:hover .group-hover\\:text-primary-dark { color: #FFFFFF; }
${D} .bg-primary, ${D} .bg-brand, ${D} .hover\\:bg-primary-dark:hover, ${D} .bg-primary-dark { color: #0A0A0A; }
${D} .bg-primary .text-white, ${D} .bg-primary.text-white, ${D} .bg-brand.text-white, ${D} .bg-primary-dark.text-white { color: #0A0A0A; }
/* Solid status fills keep their strength (white text on top) */
`;
for (const [f, ns] of [["emerald", [500, 600, 700, 800]], ["green", [500, 600]], ["amber", [500, 600, 900]], ["rose", [500, 600]], ["red", [500, 600, 700, 800]]]) {
  for (const n of ns) {
    const v = `var(--rr-o-${f}-${n})`;
    out += `${D} .bg-${f}-${n} { background-color: ${v}; }\n${D} .hover\\:bg-${f}-${n}:hover { background-color: ${v}; }\n${D} .active\\:bg-${f}-${n}:active { background-color: ${v}; }\n`;
  }
}
out += `${D} .border-emerald-600 { border-color: var(--rr-o-emerald-600); }\n${D} .border-red-600 { border-color: var(--rr-o-red-600); }
${D} ::-webkit-scrollbar-track { background: #0A0A0A; }
${D} ::-webkit-scrollbar-thumb { background: #333333; }
${D} ::-webkit-scrollbar-thumb:hover { background: #4A4A4A; }
${D} ::selection { background: rgb(255 255 255 / .28); }
${D} input, ${D} select, ${D} textarea { color-scheme: dark; }
`;
fs.writeFileSync("src/styles/theme-dark.css", out);
console.log("wrote src/styles/theme-dark.css", out.length, "bytes");
