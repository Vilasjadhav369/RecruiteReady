// Generates src/styles/theme-dark.css from Tailwind's palette.
// Run: node scripts/gen-dark-theme.mjs
import fs from "node:fs";
const theme = fs.readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const get = (fam, n) => theme.match(new RegExp(`--color-${fam}-${n}:\\s*([^;]+);`))?.[1];

const fams = { emerald: "#10b981", amber: "#f59e0b", rose: "#f43f5e", red: "#ef4444", blue: "#3b82f6", sky: "#0ea5e9", purple: "#a855f7", teal: "#14b8a6", indigo: "#6366f1", green: "#22c55e" };
const base = "#151E32";
let out = `/* AUTO-GENERATED by scripts/gen-dark-theme.mjs — do not edit by hand. */\n[data-theme="dark"] {\n  color-scheme: dark;\n`;
out += `  --rr-bg:#0B1020; --rr-surface:#151E32; --rr-surface-2:#1B2640; --rr-border:#293650; --rr-text:#F1F4FB; --rr-text-2:#A9B4C8; --rr-text-3:#7F8CA5;\n`;
// slate (inverted)
const slate = { 50: "#0F1629", 100: "#1B2540", 200: "#263250", 300: "#34415F", 400: "#7F8CA5", 500: "#94A0B8", 600: "#A9B4C8", 700: "#C2CBDB", 800: "#DBE1EC", 900: "#F1F4FB", 950: "#F8FAFF" };
for (const [k, v] of Object.entries(slate)) out += `  --color-slate-${k}: ${v};\n`;
// semantic tokens
out += `  --color-background:#0B1020; --color-bg:#0B1020; --color-brand-bg:#0B1020;
  --color-surface:#151E32; --color-brand-surface:#151E32;
  --color-ink:#F1F4FB; --color-ink-2:#A9B4C8; --color-ink-3:#7F8CA5;
  --color-text-primary:#F1F4FB; --color-text-secondary:#A9B4C8; --color-text-muted:#7F8CA5; --color-text:#F1F4FB;
  --color-brand-text:#F1F4FB; --color-brand-text-secondary:#A9B4C8; --color-brand-text-muted:#7F8CA5; --color-brand-navy:#F1F4FB; --color-navy:#F1F4FB;
  --color-border:#293650; --color-border-soft:#1F2A44; --color-brand-border:#293650;
  --color-primary-soft: color-mix(in oklab, #2563EB 14%, ${base});
  --color-primary-tint: color-mix(in oklab, #2563EB 24%, ${base});
  --color-primary-border: color-mix(in oklab, #3B82F6 38%, ${base});
  --color-brand-mint-soft: color-mix(in oklab, #2563EB 14%, ${base});
  --color-brand-mint: color-mix(in oklab, #2563EB 24%, ${base});
  --color-light-blue: color-mix(in oklab, #2563EB 14%, ${base});
  --color-brand-blue-light: color-mix(in oklab, #2563EB 14%, ${base});
  --color-primary-light:#5B9BFF;
`;
// status families: tints become translucent-on-surface, text shades get lighter
const solids = [];
for (const [f, hex] of Object.entries(fams)) {
  out += `  --color-${f}-50: color-mix(in oklab, ${hex} 12%, ${base});\n`;
  out += `  --color-${f}-100: color-mix(in oklab, ${hex} 20%, ${base});\n`;
  out += `  --color-${f}-200: color-mix(in oklab, ${hex} 34%, ${base});\n`;
  for (const [n, from] of [[600, 400], [700, 300], [800, 200], [900, 100]]) {
    const v = get(f, from); if (v) out += `  --color-${f}-${n}: ${v};\n`;
    const o = get(f, n); if (o) out += `  --rr-o-${f}-${n}: ${o};\n`;
  }
  out += `  --rr-o-${f}-500: ${get(f, 500)};\n`;
}
out += `}\n\n`;

// Class overrides (unlayered, so they beat Tailwind utilities)
const D = '[data-theme="dark"]';
out += `/* Surfaces */
${D} .bg-white, ${D} .hover\\:bg-white:hover, ${D} .focus\\:bg-white:focus { background-color: var(--rr-surface); }
${D} .bg-white\\/95 { background-color: color-mix(in oklab, var(--rr-surface) 95%, transparent); }
${D} .bg-white\\/80 { background-color: color-mix(in oklab, var(--rr-surface) 80%, transparent); }
${D} .from-white { --tw-gradient-from: var(--rr-surface); }
${D} .via-white { --tw-gradient-via: var(--rr-surface); }
${D} .ring-white { --tw-ring-color: var(--rr-surface); }
/* Intentionally-dark panels in light mode stay dark (and overlays stay dark) */
${D} .bg-slate-950 { background-color: #070B16; }
${D} .bg-slate-900 { background-color: #1B2640; }
${D} .bg-slate-800 { background-color: #26324D; }
${D} .bg-slate-900\\/40 { background-color: rgb(3 6 15 / .6); }
${D} .bg-slate-900\\/50 { background-color: rgb(3 6 15 / .68); }
${D} .hover\\:bg-slate-800:hover { background-color: #2F3D5E; }
${D} .hover\\:bg-slate-700:hover { background-color: #34415F; }
${D} .active\\:bg-slate-950:active { background-color: #070B16; }
${D} .border-slate-900 { border-color: #2A3652; }
${D} .border-slate-800 { border-color: #2A3652; }
${D} .border-slate-700 { border-color: #3A4868; }
${D} .hover\\:border-slate-600:hover { border-color: #4A5A7E; }
/* Light text that sits on dark panels must stay light */
${D} .text-slate-100 { color: #F1F5F9; }
${D} .text-slate-200, ${D} .hover\\:text-slate-200:hover { color: #E2E8F0; }
${D} .text-slate-300 { color: #CBD5E1; }
/* Brand text on soft backgrounds */
${D} .text-primary-dark, ${D} .hover\\:text-primary-dark:hover, ${D} .group:hover .group-hover\\:text-primary-dark { color: #8DB2FF; }
${D} .text-brand-dark, ${D} .hover\\:text-brand-dark:hover { color: #8DB2FF; }
${D} .text-primary { color: #6AA2FF; }
${D} .hover\\:text-primary:hover { color: #8DB2FF; }
/* Solid status fills keep their original strength (white text on top) */
`;
const solidSel = [];
for (const m of [
  ["emerald", [500, 600, 700, 800]], ["amber", [500, 600, 900]], ["rose", [500, 600]], ["red", [500, 600, 700, 800]],
  ["blue", [500]], ["sky", [500]], ["indigo", [600]],
]) {
  const [f, ns] = m;
  for (const n of ns) {
    const v = n === 500 ? `var(--rr-o-${f}-500)` : `var(--rr-o-${f}-${n})`;
    out += `${D} .bg-${f}-${n} { background-color: ${v}; }\n`;
    out += `${D} .hover\\:bg-${f}-${n}:hover { background-color: ${v}; }\n`;
    out += `${D} .active\\:bg-${f}-${n}:active { background-color: ${v}; }\n`;
    out += `${D} .bg-${f}-${n}\\/80 { background-color: color-mix(in oklab, ${v} 80%, transparent); }\n`;
  }
}
out += `${D} .border-emerald-600 { border-color: var(--rr-o-emerald-600); }\n${D} .border-red-600 { border-color: var(--rr-o-red-600); }\n`;
out += `${D} .text-emerald-500, ${D} .text-amber-500, ${D} .text-rose-500, ${D} .text-red-500 { filter: brightness(1.12); }\n`;
// native form controls / scrollbars / selection
out += `${D} ::-webkit-scrollbar-track { background: #0B1020; }
${D} ::-webkit-scrollbar-thumb { background: #34415F; }
${D} ::-webkit-scrollbar-thumb:hover { background: #4A5A7E; }
${D} ::selection { background: rgb(59 130 246 / .35); }
${D} input, ${D} select, ${D} textarea { color-scheme: dark; }
${D} img:not([data-keep]) { filter: brightness(.92); }
`;
fs.writeFileSync("src/styles/theme-dark.css", out);
console.log("wrote src/styles/theme-dark.css", out.length, "bytes");
